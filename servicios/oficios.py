def oficio_nombre(rubro, oficio):
    for clave, nombre in OFICIOS.get(rubro) or []:
        if clave == oficio:
            return nombre
    for lista in OFICIOS.values():
        for clave, nombre in lista:
            if clave == oficio:
                return nombre
    return oficio or "Servicio"


def rubro_nombre(rubro):
    for clave, nombre in RUBROS:
        if clave == rubro:
            return nombre
    return rubro or "Servicios"


def especialidades_planas():
    pares = []
    for rubro, lista in OFICIOS.items():
        for clave, nombre in lista:
            pares.append((rubro, clave, nombre))
    return pares
